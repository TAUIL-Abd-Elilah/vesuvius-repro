"""Regenerate the README results table from results/*.json.

The table and the results directory have drifted apart twice: once when PHerc0814 was
run but never tabled (the README undercounted its own evidence at ten scrolls instead
of eleven), and once when the PHerc0846A row cited region 2 while results/ held only
the anomalous region 1. Both were caught by hand. With a sweep adding rows unattended,
hand-maintenance is not good enough - so the table is generated from the evidence.

Rewrites only the block between the two markers, leaving the rest of the README alone.

Usage:
    python update_results_table.py [--results results] [--readme vesuvius-repro/README.md]
    python update_results_table.py --check      # non-zero exit if out of date
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

BEGIN = "<!-- RESULTS TABLE: generated by update_results_table.py, do not hand-edit -->"
END = "<!-- END RESULTS TABLE -->"

# region-2 reruns and the anomalous region are handled explicitly rather than by
# filename convention, so a stray file cannot quietly change the headline
ANOMALOUS = {"PHerc0846A_r1_anomalous_region"}
VOXELS = 128 ** 3


def load(results: Path) -> list[dict]:
    rows = []
    for p in sorted(results.glob("*.json")):
        stem = p.stem
        if stem.endswith("_NEW_surface-m7") or stem == "regime_calibration":
            continue
        if any(a in stem for a in ANOMALOUS):
            continue
        try:
            r = json.loads(p.read_text())
        except Exception:  # noqa: BLE001
            continue
        if "dice" not in r or "scroll" not in r:
            continue
        r["_file"] = p.name
        rows.append(r)

    # one row per scroll: keep the best-scoring region, since a second region is only
    # ever run to test whether a low score was the region or the scroll
    best: dict[str, dict] = {}
    for r in rows:
        s = r["scroll"]
        if s not in best or r["dice"] > best[s]["dice"]:
            best[s] = r
    out = list(best.values())
    out.sort(key=lambda r: (-r["dice"], r["scroll"]))
    return out


def render(rows: list[dict]) -> str:
    ok = [r for r in rows if r["dice"] > 0.99]
    bad = [r for r in rows if r["dice"] <= 0.99]
    l0 = sum(1 for r in ok if r["ct_level"] == 0)
    l2 = sum(1 for r in ok if r["ct_level"] == 2)

    lines = [BEGIN, "",
             "| scroll | CT level | Dice | disagreeing voxels | verdict |",
             "|---|---|---|---|---|"]
    for r in ok:
        n = r["disagreeing_voxels"]
        pct = 100 * n / VOXELS
        d = f"**{r['dice']:.4f}**" if r["dice"] >= 0.99995 else f"{r['dice']:.4f}"
        cell = "**0**" if n == 0 else f"{n:,} ({pct:.3f}%)"
        verdict = "reproduced exactly" if n == 0 else "reproduced"
        lines.append(f"| {r['scroll']} | L{r['ct_level']} | {d} | {cell} | {verdict} |")
    for r in bad:
        n = r["disagreeing_voxels"]
        lines.append(f"| **{r['scroll']}** | **L{r['ct_level']}** | **{r['dice']:.4f}** "
                     f"| **{n:,} ({100*n/VOXELS:.2f}%)** | **not reproduced** |")

    lines += ["",
              f"**{len(ok)} scrolls reproduce** — {l0} at CT level 0 and {l2} at level 2 "
              f"— at Dice {min(r['dice'] for r in ok):.4f}–{max(r['dice'] for r in ok):.4f}. "
              "In every one, 100% of the differing voxels lie within 0.01 of the "
              "threshold, which is what float16 storage and autocast leave behind.",
              ""]
    if bad:
        names = ", ".join(r["scroll"] for r in bad)
        lines += [f"**{names} does not reproduce.** Detail below.", ""]
    lines.append(END)
    return "\n".join(lines)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", default="results")
    ap.add_argument("--readme", default="vesuvius-repro/README.md")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    rows = load(Path(args.results))
    if not rows:
        raise SystemExit("no result JSONs found")
    table = render(rows)

    readme = Path(args.readme)
    text = readme.read_text(encoding="utf-8")
    if BEGIN not in text or END not in text:
        print(table)
        raise SystemExit(
            f"\nmarkers not found in {readme}; paste the block above where the table "
            f"belongs, keeping both marker comments, and this becomes automatic")

    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    new = head + table + tail
    if new == text:
        print(f"up to date ({len(rows)} scrolls)")
        return
    if args.check:
        print(f"OUT OF DATE: {readme} does not match {args.results}", file=sys.stderr)
        raise SystemExit(1)
    readme.write_text(new, encoding="utf-8")
    print(f"updated {readme} from {len(rows)} scrolls")


if __name__ == "__main__":
    main()
